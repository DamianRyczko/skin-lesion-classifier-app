#!/usr/bin/env python3
"""Regenerate the [theme] block of .streamlit/config.toml from ui/tokens.py.

Usage (from the project root):
    python .claude/skills/streamlit-neubrutal-ui/scripts/sync_theme.py [--project PATH]

Only the block between the BEGIN/END markers is rewritten; any other
settings in config.toml ([server], [client], ...) are kept.
"""

import argparse
import importlib.util
import re
import sys
from pathlib import Path
from types import SimpleNamespace

BEGIN = "# >>> neubrutal-theme (generated by sync_theme.py from ui/tokens.py; edit tokens.py, not this block)"
END = "# <<< neubrutal-theme"


def load_tokens(project: Path):
    path = project / "ui" / "tokens.py"
    if not path.exists():
        sys.exit(f"error: {path} not found. Run bootstrap.py first.")
    spec = importlib.util.spec_from_file_location("nb_tokens", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def theme_block(t) -> str:
    C, F = SimpleNamespace(**t.LIGHT), t.F
    body_font = f"'{F.BODY}':{F.BODY_URL}"
    mono_font = f"'{F.MONO}':{F.MONO_URL}"
    lines = [
        BEGIN,
        "[theme]",
        'base = "light"',
        f"primaryColor = {q(C.ACCENT)}",
        f"backgroundColor = {q(C.BG)}",
        f"secondaryBackgroundColor = {q(C.SIDEBAR)}",
        f"textColor = {q(C.INK)}",
        f"borderColor = {q(C.INK)}",
        f"linkColor = {q(C.ACCENT_DARK)}",
        f"dataframeHeaderBackgroundColor = {q(C.SIDEBAR)}",
        "showWidgetBorder = true",
        "showSidebarBorder = true",
        'baseRadius = "none"',
        'buttonRadius = "none"',
        f"font = {q(body_font)}",
        f"headingFont = {q(mono_font)}",
        f"codeFont = {q(mono_font)}",
        "",
        "[theme.sidebar]",
        f"backgroundColor = {q(C.SIDEBAR)}",
        f"secondaryBackgroundColor = {q(C.BG)}",
        END,
    ]
    return "\n".join(lines) + "\n"


def sync(project: Path) -> Path:
    tokens = load_tokens(project)
    cfg = project / ".streamlit" / "config.toml"
    cfg.parent.mkdir(parents=True, exist_ok=True)
    block = theme_block(tokens)
    text = cfg.read_text(encoding="utf-8") if cfg.exists() else ""

    if BEGIN in text and END in text:
        pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
        text = pattern.sub(lambda _: block, text, count=1)
    else:
        outside = text
        if re.search(r"^\s*\[theme(\.|\])", outside, re.M):
            sys.exit(f"error: {cfg} already has a [theme] section not managed by this skill.\n"
                     "Move its values into ui/tokens.py, delete the section, and run again.")
        text = block + ("\n" + text if text.strip() else "")
    cfg.write_text(text, encoding="utf-8")
    return cfg


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".", help="project root (default: current directory)")
    args = ap.parse_args()
    cfg = sync(Path(args.project).resolve())
    print(f"updated {cfg}")


if __name__ == "__main__":
    main()
